    public PixelTextRenderer(GraphicsDevice device)
    {
        pixel = new Texture2D(device, 1, 1);
        pixel.SetData(new[] { Color.White });
    }

    public void Draw(SpriteBatch batch, string text, Vector2 origin, Color color, int scale = 2)
    {
        for (var index = 0; index < text.Length; index++)
        {
            if (!Glyphs.TryGetValue(char.ToUpperInvariant(text[index]), out var glyph)) continue;
            for (var row = 0; row < 7; row++)
            {
                for (var column = 0; column < 5; column++)
                {
                    if (glyph[row * 6 + column] != '1') continue;
                    var x = (int)origin.X + (index * 6 + column) * scale;
                    var y = (int)origin.Y + row * scale;
                    batch.Draw(pixel, new Rectangle(x + 1, y + 1, scale, scale), new Color(7, 10, 18));
                    batch.Draw(pixel, new Rectangle(x, y, scale, scale), color);
                }
            }
        }
    }

    public void Dispose() => pixel.Dispose();
}
